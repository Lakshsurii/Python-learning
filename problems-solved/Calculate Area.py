def calculateAreaOfSquare(side):
    area = side*side
    return area
def calculateAreaOfCircle(radius):
    area = 3.14 * radius**2
    return area
def calculateAreaOfRectangle(length,breadth):
    area = length * breadth
    return area

print(calculateAreaOfSquare(5))
print(calculateAreaOfCircle(3))
print(calculateAreaOfRectangle(5, 4))

    
